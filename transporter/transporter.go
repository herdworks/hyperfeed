// Transporter errors
var (
	ErrNotImplemented       = errors.New("transporter: not implemented")
	ErrTransporterReadiness = errors.New("transporter: transporter not ready")
	ErrRequestReadiness     = errors.New("transporter: request not ready")
	ErrRequestExpired       = errors.New("transporter: request deadline exceeded")
	ErrInvalidRequest       = errors.New("transporter: invalid request")
	ErrTooManyRedirects     = errors.New("transporter: too many redirects")
	ErrResponse             = errors.New("transporter: response error")
	ErrResponseTooLarge     = errors.New("transporter: response body exceeds limit")
)

// Transporter defaults
var (
	DefaultConfig = &Config{
		Wait:             1000 * time.Millisecond,
		Timeout:          10 * time.Second,
		MaxRedirects:     1,
		MaxContentLength: 4 << 20, // 4 MiB
	}
	DefaultOptions = &Options{
		Headers:     map[string]string{},
		Timeout:     0,
		Redirects:   false,
		Attempt:     0,
		MaxAttempts: 1,
	}
	DefaultUserAgent     = "hyperfeed-go/transporter (+https://github.com/herdworks/hyperfeed-go)"
	DefaultAcceptHeaders = strings.Join([]string{
		"application/rss+xml",
		"application/atom+xml;q=0.9",
		"application/feed+json;q=0.8",
		"application/xml;q=0.7",
		"text/xml;q=0.5",
		"application/json;q=0.4",
		"*/*;q=0.1",
	}, ", ")
)

// Transporter orchestrates outbound HTTP requests for feeds. The struct keeps
// references to the HTTP client and configuration but intentionally avoids
// performing any logic in stub form. Once implemented, Transporter will be
// responsible for applying conditional headers, honoring rate limits, and
// extracting cache hints to share with the scheduler.
type Transporter struct {
	http.Client
	Config *Config
}

// Config captures tunable knobs for HTTP transport behavior. Every
// field in this struct is persisted so the scheduler can reconstruct request
// plans deterministically across restarts.
type Config struct {
	// Wait specifies the default wait time between requests to the same host.
	// This protects origin servers from being overwhelmed by bursts of traffic.
	Wait time.Duration

	// Timeout specifies the default timeout for HTTP requests.
	// If zero, the implementation must fall back to a safe default that balances resiliency with server friendliness.
	Timeout time.Duration

	// MaxRedirects constrains the number of redirects followed for a single request.
	// This protects origin servers from loops and prevents the transporter from amplifying traffic.
	MaxRedirects int

	// MaxContentLength caps the number of bytes that will be buffered in memory for a single response.
	// Implementations must stream to disk or abort once this limit is reached.
	MaxContentLength int64
}

// Request is the immutable description of a fetch attempt.
// Scheduler produces this snapshot so the transporter can run without needing broader scheduler context.
type Request struct {
	// *http.Request is the fully constructed HTTP request, ready for dispatch.
	*http.Request

	// Request.URL == Request.Request.URL

	// CreatedAt records when the request was built.
	CreatedAt time.Time

	// Conditions enumerate the validators that should be attached to the HTTP request as conditional headers.
	Conditions []*Condition

	// Options allows per-request overrides without mutating global Options.
	Options Options
}

// Options holds options for individual requests. These are
// generated by the scheduler for each fetch attempt and allow per-plan
// overrides without mutating global Options.
type Options struct {
	// Headers specifies additional headers to include in the request.
	// The transporter must merge these with conditional headers derived from persisted state while deduplicating case-insensitively.
	Headers map[string]string

	// Deadline expresses the hard cutoff for completing the exchange. The transporter should map this into context timeouts.
	Timeout time.Duration

	// Redirects enables or disables following redirects for this request.
	// When disabled, the transporter must return the 3xx response as-is.
	Redirects bool

	// Attempt tracks which retry attempt this request represents.
	Attempt int

	// MaxAttempts is the retry budget allocated for this tick.
	MaxAttempts int
}

type Condition struct {
	Kind          ConditionKind
	Name          string
	Value         string
	Values        []string
	DurationValue time.Duration
	TimeValue     time.Time
	Algorithm     string
}

type ConditionKind string

const (
	ConditionLastOK            ConditionKind = "last-ok"
	ConditionMinInterval       ConditionKind = "min-interval"
	ConditionMaxInterval       ConditionKind = "max-interval"
	ConditionDigest            ConditionKind = "digest"
	ConditionContentLength     ConditionKind = "content-length"
	ConditionIfNoneMatchStrong ConditionKind = "if-none-match-strong"
	ConditionIfNoneMatchWeak   ConditionKind = "if-none-match-weak"
	ConditionIfNoneMatch       ConditionKind = "if-none-match"
	ConditionIfMatch           ConditionKind = "if-match"
	ConditionIfModifiedSince   ConditionKind = "if-modified-since"
	ConditionIfUnmodifiedSince ConditionKind = "if-unmodified-since"
	ConditionIfRange           ConditionKind = "if-range"
	ConditionCustomHeader      ConditionKind = "custom-header"
)

type RedirectTracker struct {
	max   int
	base  func(*http.Request, []*http.Request) error
	chain []*url.URL
}

// Response captures the outcome of executing a Request. It wraps the raw HTTP
// response along with derived metadata so callers can persist updates without
// re-parsing headers.
type Response struct {
	*http.Response

	// StatusCode is copied from Raw for convenience when Raw is present.
	StatusCode int

	// Headers contains all response headers as received.
	Headers http.Header

	// Body holds payload bytes when the transporter buffers content in memory.
	Body []byte

	// ReceivedAt records when the response completed.
	ReceivedAt time.Time

	// Duration is the round-trip time from request dispatch to final byte.
	Duration time.Duration

	// BodyDigest contains a digest of the payload when downloaded.
	BodyDigest string

	// BodyDigestAlgorithm identifies the algorithm used for BodyDigest.
	BodyDigestAlgorithm string

	// RedirectChain records intermediate redirects followed during the request.
	RedirectChain []*url.URL

	// NetworkError captures transport-level failures separate from HTTP status codes.
	NetworkError error
}

// ========================== Transporter Methods =============================

// NewClient returns a request-scoped copy of the transporter's HTTP client and
// lazily initializes configuration defaults on first use.
func (t *Transporter) NewClient() *http.Client {
	if t == nil {
		return &http.Client{}
	}
	if t.Config == nil {
		t.Config = DefaultConfig
	}
	if t.Config.Timeout <= 0 {
		t.Config.Timeout = DefaultConfig.Timeout
	}
	if t.Config.MaxRedirects <= 0 {
		t.Config.MaxRedirects = DefaultConfig.MaxRedirects
	}
	if t.Config.MaxContentLength <= 0 {
		t.Config.MaxContentLength = DefaultConfig.MaxContentLength
	}
	if t.Timeout == 0 && t.Config.Timeout > 0 {
		t.Timeout = t.Config.Timeout
	}
	clone := t.Client // shallow copy
	return &clone
}

// Get fetches the content at the given href using the package HTTP client.
func (t *Transporter) Get(ctx context.Context, request *Request) (*Response, error) {
	var client *http.Client = t.NewClient()
	var response *Response = &Response{}
	var err error
	if t == nil {
		return nil, ErrTransporterReadiness
	}
	if response.Response, err = client.Do(request.Request); err != nil {
		return nil, errors.Join(ErrResponse, fmt.Errorf("perform request: %w", err))
	}
	if response.StatusCode >= 200 && response.Response.StatusCode < 300 {
		return nil, errors.Join(ErrResponse, fmt.Errorf("unexpected status: %s", response.Status))
	}
	return response, nil
}

// Fetch performs the HTTP exchange for the provided request.
// If the request is not ready, a typed error such as ErrRequestReadiness must be returned.
func (t *Transporter) Fetch(ctx context.Context, request *Request) (*Response, error) {
	var client *http.Client = t.NewClient()
	var tracker *RedirectTracker
	var response *Response = &Response{}
	var err error
	if t == nil {
		return nil, ErrInvalidRequest
	}
	preparedRequest, cancels, err := t.Prepare(ctx, request)
	if err != nil {
		return nil, err
	}
	for _, cancel := range cancels {
		defer cancel()
	}

	ready, err := request.Valid()
	if err != nil {
		return nil, err
	}
	if !ready {
		return nil, ErrRequestReadiness
	}

	tracker = &RedirectTracker{
		max:  t.Config.MaxRedirects,
		base: client.CheckRedirect,
	}
	client.CheckRedirect = tracker.Track

	start := time.Now()
	resp, err := client.Do(preparedRequest)
	if err != nil {
		if errors.Is(err, ErrTooManyRedirects) {
			return nil, ErrTooManyRedirects
		}
		return nil, err
	}

	body, err := readResponseBody(resp.Body, t.Config.MaxContentLength)
	if err != nil {
		return nil, err
	}

	resp.Body = io.NopCloser(bytes.NewReader(body))
	resp.ContentLength = int64(len(body))

	receivedAt := time.Now()
	headers := resp.Header.Clone()
	duration := receivedAt.Sub(start)

	response = &Response{
		Response:      resp,
		StatusCode:    resp.StatusCode,
		Headers:       headers,
		Body:          body,
		ReceivedAt:    receivedAt,
		Duration:      duration,
		RedirectChain: tracker.Snapshot(),
	}

	if bodyDigest, algorithm := computeBodyDigest(body); bodyDigest != "" {
		response.BodyDigest = bodyDigest
		response.BodyDigestAlgorithm = algorithm
	}

	return response, nil
}

func (t *Transporter) Prepare(ctx context.Context, request *Request) (*http.Request, []context.CancelFunc, error) {
	if request == nil {
		return nil, nil, ErrInvalidRequest
	}
	if request.Request == nil {
		return nil, nil, ErrInvalidRequest
	}

	baseCtx := ctx
	if baseCtx == nil {
		baseCtx = context.Background()
	}

	cloned := request.Request.Clone(baseCtx)
	if cloned.Method == "" {
		cloned.Method = http.MethodGet
	}

	var cancels []context.CancelFunc
	currentCtx := cloned.Context()

	if request.Options.Timeout > time.Duration(0) {
		// TODO: Apply per-request timeout if set
	}

	if currentCtx != cloned.Context() {
		cloned = cloned.WithContext(currentCtx)
	}

	request.Header = mergeHeaders(cloned.Header)
	request.Request = cloned

	return cloned, cancels, nil
}

// ========================= Request Methods =============================

// Valid performs transporter-side preflight checks to confirm the request can execute safely.
// Implementations must return ErrRequestReadiness when the request should be postponed without counting against error budgets.
// The stub returns ErrNotImplemented until real logic is added.
func (request *Request) Valid() (bool, error) {
	if request == nil {
		return false, ErrInvalidRequest
	}
	if request.Request == nil {
		return false, ErrInvalidRequest
	}
	if request.Request.URL == nil {
		return false, ErrInvalidRequest
	}
	return true, nil
}

// ========================= Condition Methods ===========================

// Header converts the condition into an HTTP header representation when the kind maps to a standard conditional header.
func (condition *Condition) Header() http.Header {
	var headers http.Header = http.Header{}
	if condition.HasHeader() && condition.HeaderName() != "" {
		headers.Set(condition.HeaderName(), condition.HeaderValue())
	}
	return headers
}

// HasHeader reports whether the condition kind maps to a standard conditional header.
func (condition *Condition) HasHeader() bool {
	if condition == nil {
		return false
	}
	if condition.HeaderName() == "" {
		return false
	}
	switch condition.Kind {
	case ConditionIfNoneMatch, ConditionIfModifiedSince:
		return true
	case ConditionLastOK, ConditionMinInterval, ConditionMaxInterval:
		fallthrough // internal use conditions (no header)
	default:
		return false
	}
}

// HeaderName returns the HTTP header associated with the condition kind. When
// the condition only carries metadata the empty string is returned.
func (condition *Condition) HeaderName() string {
	if condition == nil {
		return ""
	}
	switch condition.Kind {
	case ConditionIfNoneMatch:
		return "If-None-Match"
	case ConditionIfModifiedSince:
		return "If-Modified-Since"
	default:
		return ""
	}
}

// HeaderValue returns the canonical header value for the condition. Metadata
// entries produce an empty string so callers can ignore them.
func (condition *Condition) HeaderValue() string {
	var values []string = []string{}
	if condition == nil {
		return strings.Join(values, ", ")
	}
	switch condition.Kind {
	// string-value conditions
	case ConditionIfNoneMatch:
		var raw []string = append([]string{condition.Value}, condition.Values...)
		if condition.Value != "" {
			values = append(values, etagValues(raw...)...)
		}

	// time-value conditions
	case ConditionIfModifiedSince:
		if !condition.TimeValue.IsZero() {
			values = append(values, fmt.Sprintf("%q", condition.TimeValue.UTC().Format(http.TimeFormat)))
		}
	}
	return strings.Join(values, ", ")
}

// ========================= Helper Functions ===========================

// mergeHeaders combines multiple http.Header maps into one.
// Duplicate header names are case-insensitively deduplicated (last one wins).
func mergeHeaders(incoming ...http.Header) http.Header {
	var merged http.Header = http.Header{}
	for _, headers := range incoming {
		if headers == nil {
			continue
		}
		for name, values := range headers {
			var exists = merged.Get(name) != ""
			for index, value := range values {
				if exists && index == 0 {
					merged.Set(name, value) // replace existing value
				} else {
					merged.Add(name, value) // append value
				}
			}
		}
	}
	return merged
}

// etagValues normalizes a list of ETag values.
func etagValues(incoming ...string) []string {
	var values []string
	for _, value := range incoming {
		var weak bool = strings.HasPrefix(value, "W/")
		value = strings.TrimLeft(value, "W/") // strip weak comparison prefix
		value = strings.TrimLeft(value, "\"")
		value = strings.TrimRight(value, "\"")
		if value == "" {
			continue // skip empty etags
		}
		value = fmt.Sprintf("%q", value) // restore quotes
		if weak {
			value = "W/" + value
		}
		values = append(values, value)
	}
	return values
}

func readResponseBody(reader io.ReadCloser, maxSize int64) ([]byte, error) {
	if reader == nil {
		return nil, nil
	}
	defer reader.Close()

	if maxSize <= 0 {
		return io.ReadAll(reader)
	}

	limited := &io.LimitedReader{R: reader, N: maxSize + 1}
	data, err := io.ReadAll(limited)
	if err != nil {
		return nil, err
	}
	if int64(len(data)) > maxSize {
		return nil, ErrResponseTooLarge
	}
	return data, nil
}

func computeBodyDigest(body []byte) (string, string) {
	hash := sha256.Sum256(body)
	digest := base64.StdEncoding.EncodeToString(hash[:])
	return digest, "sha-256"
}

func splitHeaderValues(values []string) []string {
	var result []string
	for _, value := range values {
		for _, entry := range strings.Split(value, ",") {
			trimmed := strings.TrimSpace(entry)
			if trimmed == "" {
				continue
			}
			result = append(result, trimmed)
		}
	}
	return result
}

func firstNonEmpty(values []string) string {
	for _, value := range values {
		trimmed := strings.TrimSpace(value)
		if trimmed != "" {
			return trimmed
		}
	}
	return ""
}

func cloneURL(u *url.URL) *url.URL {
	if u == nil {
		return nil
	}
	cloned := *u
	return &cloned
}

func applyDeadline(ctx context.Context, deadline time.Time) (context.Context, context.CancelFunc, error) {
	if deadline.IsZero() {
		return ctx, nil, nil
	}
	if ctx == nil {
		ctx = context.Background()
	}
	if time.Now().After(deadline) {
		return nil, nil, ErrRequestExpired
	}
	if current, ok := ctx.Deadline(); ok && !deadline.Before(current) {
		return ctx, nil, nil
	}
	nextCtx, cancel := context.WithDeadline(ctx, deadline)
	return nextCtx, cancel, nil
}

func applyTimeout(ctx context.Context, timeout time.Duration) (context.Context, context.CancelFunc) {
	if timeout <= 0 {
		return ctx, nil
	}
	if ctx == nil {
		ctx = context.Background()
	}
	deadline := time.Now().Add(timeout)
	if current, ok := ctx.Deadline(); ok && !deadline.Before(current) {
		return ctx, nil
	}
	nextCtx, cancel := context.WithDeadline(ctx, deadline)
	return nextCtx, cancel
}

func (tracker *RedirectTracker) Track(req *http.Request, via []*http.Request) error {
	if req != nil && req.URL != nil {
		tracker.chain = append(tracker.chain, cloneURL(req.URL))
	}
	if tracker.max > 0 && len(via) >= tracker.max {
		return ErrTooManyRedirects
	}
	if tracker.base != nil {
		return tracker.base(req, via)
	}
	return nil
}

func (tracker *RedirectTracker) Snapshot() []*url.URL {
	if tracker == nil || len(tracker.chain) == 0 {
		return nil
	}
	snapshot := make([]*url.URL, len(tracker.chain))
	for i, u := range tracker.chain {
		snapshot[i] = cloneURL(u)
	}
	return snapshot
}
