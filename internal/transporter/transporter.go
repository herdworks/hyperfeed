// ============================ Package Types =================================

// Transporter orchestrates outbound HTTP requests for feeds. The struct keeps
// references to the HTTP client and configuration but intentionally avoids
// performing any logic in stub form. Once implemented, Transporter will be
// responsible for applying conditional headers, honoring rate limits, and
// extracting cache hints to share with the scheduler.
type Transporter struct {
	*http.Client
	Config *Config
}

// Config captures tunable knobs for HTTP transport behavior. Every
// field in this struct is persisted so the scheduler can reconstruct request
// plans deterministically across restarts.
type Config struct {
	// Wait specifies the default wait time between requests to the same host.
	// This protects origin servers from being overwhelmed by bursts of traffic.
	Wait time.Duration

	// Timeout specifies the default timeout for HTTP requests.
	// If zero, the implementation must fall back to a safe default that balances resiliency with server friendliness.
	Timeout time.Duration

	// MaxRedirects constrains the number of redirects followed for a single request.
	// This protects origin servers from loops and prevents the transporter from amplifying traffic.
	MaxRedirects int

	// MaxContentLength caps the number of bytes that will be buffered in memory for a single response.
	// Implementations must stream to disk or abort once this limit is reached.
	MaxContentLength int64
}

// Request is the immutable description of a fetch attempt.
// Scheduler produces this snapshot so the transporter can run without needing broader scheduler context.
type Request struct {
	// *http.Request is the fully constructed HTTP request, ready for dispatch.
	*http.Request

	// URL
	URL *url.URL

	// CreatedAt records when the request was built.
	CreatedAt time.Time

	// Conditions enumerate the validators that should be attached to the HTTP request as conditional headers.
	Conditions []Condition

	// Options allows per-request overrides without mutating global Options.
	Options Options
}

// Options holds options for individual requests. These are
// generated by the scheduler for each fetch attempt and allow per-plan
// overrides without mutating global Options.
type Options struct {
	// Headers specifies additional headers to include in the request.
	// The transporter must merge these with conditional headers derived from persisted state while deduplicating case-insensitively.
	Headers http.Header

	// Deadline expresses the hard cutoff for completing the exchange. The transporter should map this into context timeouts.
	Timeout time.Duration

	// Redirects enables or disables following redirects for this request.
	// When disabled, the transporter must return the 3xx response as-is.
	Redirects bool

	// Attempt tracks which retry attempt this request represents.
	Attempt int

	// MaxAttempts is the retry budget allocated for this tick.
	MaxAttempts int
}

type Condition struct {
	Kind          ConditionKind
	Name          string
	Value         string
	Values        []string
	DurationValue time.Duration
	TimeValue     time.Time
	Algorithm     string
}

type ConditionKind string

type RedirectTracker struct {
	max   int
	base  func(*http.Request, []*http.Request) error
	chain []*url.URL
}

// Response captures the outcome of executing a Request. It wraps the raw HTTP
// response along with derived metadata so callers can persist updates without
// re-parsing headers.
type Response struct {
	*http.Response

	// Headers contains all response headers as received.
	Headers http.Header

	// Bytes holds payload bytes when the transporter buffers content in memory.
	Bytes []byte

	// ReceivedAt records when the response completed.
	ReceivedAt time.Time

	// Duration is the round-trip time from request dispatch to final byte.
	Duration time.Duration

	// RedirectChain records intermediate redirects followed during the request.
	RedirectChain []*url.URL

	// NetworkError captures transport-level failures separate from HTTP status codes.
	NetworkError error
}

