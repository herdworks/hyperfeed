// Valid performs transporter-side preflight checks to confirm the request can execute safely.
// Implementations must return ErrRequestReadiness when the request should be postponed without counting against error budgets.
// The stub returns ErrNotImplemented until real logic is added.
func (request *Request) Valid() (bool, error) {
	if request == nil {
		return false, ErrInvalidRequest
	}
	if request.Request == nil {
		return false, ErrInvalidRequest
	}
	if request.Request.URL == nil {
		return false, ErrInvalidRequest
	}
	return true, nil
}

// ========================= Condition Methods ===========================

// Header converts the condition into an HTTP header representation when the kind maps to a standard conditional header.
func (condition *Condition) Header() http.Header {
	var headers http.Header = http.Header{}
	if condition.HasHeader() && condition.HeaderName() != "" {
		headers.Set(condition.HeaderName(), condition.HeaderValue())
	}
	return headers
}

// HasHeader reports whether the condition kind maps to a standard conditional header.
func (condition *Condition) HasHeader() bool {
	if condition == nil {
		return false
	}
	if condition.HeaderName() == "" {
		return false
	}
	switch condition.Kind {
	case ConditionIfNoneMatch, ConditionIfModifiedSince:
		return true
	case ConditionLastOK, ConditionMinInterval, ConditionMaxInterval:
		fallthrough // internal use conditions (no header)
	default:
		return false
	}
}

// HeaderName returns the HTTP header associated with the condition kind. When
// the condition only carries metadata the empty string is returned.
func (condition *Condition) HeaderName() string {
	if condition == nil {
		return ""
	}
	switch condition.Kind {
	case ConditionIfNoneMatch:
		return "If-None-Match"
	case ConditionIfModifiedSince:
		return "If-Modified-Since"
	default:
		return ""
	}
}

// HeaderValue returns the canonical header value for the condition. Metadata
// entries produce an empty string so callers can ignore them.
func (condition *Condition) HeaderValue() string {
	var values []string = []string{}
	if condition == nil {
		return strings.Join(values, ", ")
	}
	switch condition.Kind {
	// string-value conditions
	case ConditionIfNoneMatch:
		var raw []string = append([]string{condition.Value}, condition.Values...)
		if condition.Value != "" {
			values = append(values, etagValues(raw...)...)
		}

	// time-value conditions
	case ConditionIfModifiedSince:
		if !condition.TimeValue.IsZero() {
			values = append(values, fmt.Sprintf("%q", condition.TimeValue.UTC().Format(http.TimeFormat)))
		}
	}
	return strings.Join(values, ", ")
}

// ========================= RedirectTracker Methods ====================
func (tracker *RedirectTracker) Track(req *http.Request, via []*http.Request) error {
	if req != nil && req.URL != nil {
		u := *req.URL // deep copy
		tracker.chain = append(tracker.chain, &u)
	}
	if tracker.max > 0 && len(via) >= tracker.max {
		return ErrTooManyRedirects
	}
	if tracker.base != nil {
		return tracker.base(req, via)
	}
	return nil
}

func (tracker *RedirectTracker) Snapshot() []*url.URL {
	if tracker == nil || len(tracker.chain) == 0 {
		return nil
	}
	snapshot := make([]*url.URL, len(tracker.chain))
	for i, u := range tracker.chain {
		cloned := *u // deep copy
		snapshot[i] = &cloned
	}
	return snapshot
}

// ============================= Response Methods =============================

// Attempted reports whether the request was event attempted (i.e. StatusCode >= 100).
func (response *Response) Attempted() bool {
	if response == nil || response.Response == nil {
		return false
	}
	return response.Response.StatusCode >= 100
}

// OK reports whether the response was successful (2xx).
func (response *Response) OK() bool {
	if response == nil || response.Response == nil {
		return false
	}
	return response.Response.StatusCode >= 200 && response.Response.StatusCode < 300
}

// Redirected reports whether the response was a redirect (3xx).
func (response *Response) Redirected() bool {
	if response == nil || response.Response == nil {
		return false
	}
	return response.Response.StatusCode >= 300 && response.Response.StatusCode < 400
}

// NotModified reports whether the response was a 304 Not Modified.
func (response *Response) NotModified() bool {
	if response == nil || response.Response == nil {
		return false
	}
	return response.Response.StatusCode == http.StatusNotModified
}

// ETags extracts and normalizes ETag values from the response headers.
// If no ETag headers are present, an empty slice is returned.
func (response *Response) ETags() []string {
	if response == nil || response.Response == nil {
		return nil
	}
	var raw []string = response.Response.Header.Values("ETag")
	return etagValues(raw...)
}

// LastModified returns the Last-Modified header as a time.Time value.
func (response *Response) LastModified() time.Time {
	if response == nil || response.Response == nil {
		return time.Time{}
	}
	return headerTimeValue(response.Response.Header, "Last-Modified")
}

// WaitUntil returns the Retry-After header as a time.Time value.
func (response *Response) WaitUntil() (date time.Time) {
	if response == nil || response.Response == nil {
		return time.Time{}
	}
	return headerTimeValue(response.Response.Header, "Retry-After")
}

// RetryAfter returns the Retry-After header as a time.Duration value.
func (response *Response) RetryAfter() (duration time.Duration) {
	if response == nil || response.Response == nil {
		return 0
	}
	return headerDurationValue(response.Response.Header, "Retry-After")
}

// PollInterval returns the X-Poll-Interval header as a time.Duration value.
func (response *Response) PollInterval() (duration time.Duration) {
	if response == nil || response.Response == nil {
		return 0
	}
	return headerDurationValue(response.Response.Header, "X-Poll-Interval")
}

// ========================= Helper Functions ===========================

// mergeHeaders combines multiple http.Header maps into one.
// Duplicate header names are case-insensitively deduplicated (last one wins).
func mergeHeaders(incoming ...http.Header) http.Header {
	var merged http.Header = http.Header{}
	for _, headers := range incoming {
		if headers == nil {
			continue
		}
		for name, values := range headers {
			var exists = merged.Get(name) != ""
			name = http.CanonicalHeaderKey(name)
			for index, value := range values {
				if exists && index == 0 {
					merged.Set(name, value) // replace existing value
				} else {
					merged.Add(name, value) // append value
				}
			}
		}
	}
	return merged
}

// etagValues normalizes a list of ETag values.
func etagValues(incoming ...string) []string {
	var values []string
	for _, value := range incoming {
		var weak bool = strings.HasPrefix(value, "W/")
		value = strings.TrimLeft(value, "W/") // strip weak comparison prefix
		value = strings.TrimLeft(value, "\"")
		value = strings.TrimRight(value, "\"")
		if value == "" {
			continue // skip empty etags
		}
		value = fmt.Sprintf("%q", value) // restore quotes
		if weak {
			value = "W/" + value
		}
		values = append(values, value)
	}
	return values
}

func headerDurationValue(headers http.Header, name string) (duration time.Duration) {
	var err error
	if value := headers.Get(name); value == "" {
		return 0
	} else if duration, err = time.ParseDuration(value + "s"); err != nil {
		return 0
	}
	return duration
}

func headerTimeValue(headers http.Header, name string) (date time.Time) {
	var err error
	if value := headers.Get(name); value == "" {
		return time.Time{}
	} else if date, err = time.Parse(http.TimeFormat, value); err != nil {
		return time.Time{}
	}
	return date
}

func applyContextTimeout(ctx context.Context, timeouts ...time.Duration) (context.Context, context.CancelFunc) {
	if ctx == nil || len(timeouts) == 0 || slices.Min(timeouts) <= 0 {
		return ctx, nil
	}
	return applyContextDeadline(ctx, time.Now().Add(slices.Min(timeouts)))
}

func applyContextDeadline(ctx context.Context, deadline time.Time) (context.Context, context.CancelFunc) {
	if ctx == nil || deadline.IsZero() || time.Now().After(deadline) {
		return ctx, nil
	}
	if current, ok := ctx.Deadline(); ok && !deadline.Before(current) {
		return ctx, nil
	}
	new, cancellation := context.WithDeadline(ctx, deadline)
	return new, cancellation
}

func isVendoredResponseHeader(name string) bool {
	var vendors = map[string]string{
		"Amazon":     "X-Amz-",
		"Cloudflare": "Cf-",
	}
	for _, prefix := range vendors {
		if strings.HasPrefix(http.CanonicalHeaderKey(name), prefix) {
			return true
		}
	}
	return false
}

func isDeprecatedResponseHeader(name string) bool {
	var deprecated = []string{
		"Report-To",
		"X-Pingback",
		"X-Powered-By",
		"X-AspNet-Version",
		"X-AspNetMvc-Version",
		"X-Generator",
	}
	return slices.Contains(deprecated, http.CanonicalHeaderKey(name))
}

func isExperimentalResponseHeader(name string) bool {
	var experimental = []string{
		"Nel",
	}
	return slices.Contains(experimental, http.CanonicalHeaderKey(name))
}

